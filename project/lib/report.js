import PDFDocument from 'pdfkit';

const NAVY = '#0b1220';
const ACCENT = '#1f3a6b';
const ACCENT_2 = '#2b6e4f';
const MUTED = '#6b7a90';
const LIGHT = '#f3f5f9';
const RULE = '#dde3ee';

function stripMarkdown(text) {
  return (text || '')
    .replace(/\*\*(.+?)\*\*/g, '$1')
    .replace(/\*(.+?)\*/g, '$1')
    .replace(/`(.+?)`/g, '$1');
}

function splitSections(answer) {
  const lines = (answer || '').split(/\r?\n/);
  const sections = [];
  let current = { heading: null, body: [] };
  const headingRe = /^\s*(?:[1-9][.)]\s+|##?\s+|[A-Z][A-Z0-9 \-]{4,}:?\s*$|\*\*([^*]+)\*\*\s*:?\s*$)/;

  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed) {
      current.body.push('');
      continue;
    }
    if (headingRe.test(trimmed) && trimmed.length < 90) {
      if (current.heading || current.body.some((l) => l.trim())) {
        sections.push(current);
      }
      current = {
        heading: stripMarkdown(trimmed.replace(/^#+\s*|\*\*/g, '').replace(/[:.]?\s*$/, '')),
        body: [],
      };
    } else {
      current.body.push(line);
    }
  }
  if (current.heading || current.body.some((l) => l.trim())) {
    sections.push(current);
  }
  return sections;
}

function drawHeader(doc, opts) {
  const { title, subtitle } = opts;
  doc.save();
  doc.rect(0, 0, doc.page.width, 90).fill(NAVY);
  doc.fillColor('white').font('Helvetica-Bold').fontSize(22).text(title, 50, 28);
  doc.fillColor('#a9b6cf').font('Helvetica').fontSize(11).text(subtitle, 50, 58);
  doc.restore();
  doc.moveDown(2);
}

function drawFooter(doc) {
  const range = doc.bufferedPageRange();
  for (let i = range.start; i < range.start + range.count; i++) {
    doc.switchToPage(i);
    const y = doc.page.height - 40;
    doc
      .save()
      .fillColor(MUTED)
      .font('Helvetica')
      .fontSize(9)
      .text(
        'Generated by Compliance Assistant · AI-assisted draft · Human review required',
        50,
        y,
        { align: 'left', lineBreak: false },
      )
      .text(`Page ${i - range.start + 1} of ${range.count}`, 50, y, {
        align: 'right',
        lineBreak: false,
        width: doc.page.width - 100,
      })
      .restore();
  }
}

function drawMetaBox(doc, rows) {
  const left = 50;
  const right = doc.page.width - 50;
  const padding = 14;
  const startY = doc.y;

  doc.save();
  doc.fillColor(LIGHT).rect(left, startY, right - left, 1).fill();
  let y = startY + padding;

  doc.fillColor(LIGHT).rect(left, startY, right - left, 0).fill();

  for (const [label, value] of rows) {
    doc
      .fillColor(MUTED)
      .font('Helvetica-Bold')
      .fontSize(9)
      .text(label.toUpperCase(), left + padding, y, {
        width: 110,
        lineBreak: false,
        characterSpacing: 1,
      });
    doc
      .fillColor(NAVY)
      .font('Helvetica')
      .fontSize(11)
      .text(value, left + padding + 120, y, {
        width: right - left - padding * 2 - 120,
      });
    y = doc.y + 8;
  }

  const totalHeight = y - startY;
  doc.fillColor(LIGHT).rect(left, startY, right - left, totalHeight).fill();
  doc.strokeColor(RULE).lineWidth(1).rect(left, startY, right - left, totalHeight).stroke();

  let yy = startY + padding;
  for (const [label, value] of rows) {
    doc
      .fillColor(MUTED)
      .font('Helvetica-Bold')
      .fontSize(9)
      .text(label.toUpperCase(), left + padding, yy, {
        width: 110,
        lineBreak: false,
        characterSpacing: 1,
      });
    doc
      .fillColor(NAVY)
      .font('Helvetica')
      .fontSize(11)
      .text(value, left + padding + 120, yy, {
        width: right - left - padding * 2 - 120,
      });
    yy = doc.y + 8;
  }

  doc.restore();
  doc.y = startY + totalHeight + 16;
}

function drawSection(doc, section, idx) {
  if (section.heading) {
    doc.moveDown(0.5);
    doc
      .fillColor(ACCENT_2)
      .font('Helvetica-Bold')
      .fontSize(9)
      .text(`SECTION ${idx + 1}`, 50, doc.y, { characterSpacing: 1.5 });
    doc
      .fillColor(NAVY)
      .font('Helvetica-Bold')
      .fontSize(15)
      .text(section.heading, 50, doc.y + 2);
    doc.moveDown(0.4);
    doc.strokeColor(ACCENT).lineWidth(2).moveTo(50, doc.y).lineTo(110, doc.y).stroke();
    doc.moveDown(0.6);
  }

  const bodyText = stripMarkdown(section.body.join('\n')).trim();
  if (bodyText) {
    doc
      .fillColor('#1a2540')
      .font('Helvetica')
      .fontSize(11)
      .text(bodyText, 50, doc.y, {
        width: doc.page.width - 100,
        align: 'left',
        lineGap: 3,
      });
    doc.moveDown(0.6);
  }
}

export function buildAuditReport({
  title = 'Compliance Audit Report',
  subject,
  question,
  answer,
  repo,
  branch,
  filesScanned,
  frameworks = [],
  kind = 'compliance',
}) {
  const doc = new PDFDocument({
    size: 'LETTER',
    margins: { top: 50, bottom: 60, left: 50, right: 50 },
    bufferPages: true,
    info: {
      Title: title,
      Author: 'Compliance Assistant',
      Subject: subject || 'Compliance audit',
      Keywords: 'PCI-DSS, GDPR, HIPAA, compliance, audit',
    },
  });

  const chunks = [];
  doc.on('data', (c) => chunks.push(c));
  const done = new Promise((resolve, reject) => {
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);
  });

  const dateStr = new Date().toLocaleString('en-US', {
    dateStyle: 'long',
    timeStyle: 'short',
  });

  drawHeader(doc, {
    title,
    subtitle:
      (kind === 'modernize'
        ? 'Legacy System Assessment for Modernization Planning'
        : 'Regulatory Compliance Audit for Management Review') +
      ' · ' +
      dateStr,
  });

  const filesList = filesScanned && filesScanned.length
    ? filesScanned.length > 10
      ? `${filesScanned.slice(0, 10).join(', ')} (+${filesScanned.length - 10} more)`
      : filesScanned.join(', ')
    : 'n/a';

  const frameworksList = frameworks && frameworks.length > 0
    ? frameworks.join(', ')
    : 'PCI-DSS, GDPR, HIPAA';

  const metaRows = [];
  metaRows.push(['Subject', subject || 'Bundled Sample Systems']);
  if (repo) metaRows.push(['Repository', branch ? `${repo} @ ${branch}` : repo]);
  if (kind === 'compliance') {
    metaRows.push(['Frameworks', frameworksList]);
  }
  metaRows.push(['Audit Scope', question || '(comprehensive assessment)']);
  metaRows.push(['Systems Reviewed', filesList]);
  metaRows.push(['Analysis Engine', 'Google Gemini · gemini-flash-latest']);

  drawMetaBox(doc, metaRows);

  doc
    .fillColor('#8a4b08')
    .font('Helvetica-Bold')
    .fontSize(9)
    .text('PRELIMINARY AI-GENERATED ANALYSIS — NOT A COMPLIANCE ATTESTATION', 50, doc.y);
  doc
    .fillColor(MUTED)
    .font('Helvetica')
    .fontSize(9)
    .text('Findings and framework mappings require independent human verification against system scope, runtime behavior, applicable requirements, and compensating controls. This report is not legal advice and does not determine regulatory penalties or organization-wide compliance.', 50, doc.y + 4, { width: doc.page.width - 100 });
  doc.moveDown(1.2);

  doc
    .fillColor(NAVY)
    .font('Helvetica-Bold')
    .fontSize(14)
    .text('Findings', 50, doc.y);
  doc.moveDown(0.4);
  doc.strokeColor(ACCENT).lineWidth(2).moveTo(50, doc.y).lineTo(110, doc.y).stroke();
  doc.moveDown(0.8);

  const sections = splitSections(answer);
  if (!sections.length) {
    doc
      .fillColor('#1a2540')
      .font('Helvetica')
      .fontSize(11)
      .text(stripMarkdown(answer || '(no answer)'), 50, doc.y, {
        width: doc.page.width - 100,
        lineGap: 3,
      });
  } else {
    sections.forEach((s, i) => drawSection(doc, s, i));
  }

  drawFooter(doc);
  doc.end();
  return done;
}